from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Optional, Dict, Any


@dataclass
class TTSResult:
    """Represents synthesized audio with metadata for HTTP response and telemetry."""
    audio_bytes: bytes
    media_type: str             # "audio/wav" or "audio/mpeg"
    provider: str               # "voicetut" or "edge-tts"
    voice: str                  # e.g. "Ahmed", "ar-EG-SalmaNeural"
    duration_ms: float          # Milliseconds taken for synthesis
    is_fallback: bool = False   # True if this audio was generated by the fallback provider
    metadata: Dict[str, Any] = field(default_factory=dict)


class BaseTTSProvider(ABC):
    """Abstract base class for Text-to-Speech synthesis providers."""

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Unique provider identifier."""
        pass

    @abstractmethod
    async def synthesize(
        self,
        text: str,
        voice: Optional[str] = None,
        rate: Optional[str] = None,
    ) -> Optional[TTSResult]:
        """
        Synthesizes text into audio bytes.
        Returns TTSResult if successful, or None on any failure.
        Must handle its own exceptions without leaking or raising to the caller.
        """
        pass

    @abstractmethod
    def is_available(self) -> bool:
        """Checks if the provider is configured and available for requests."""
        pass

